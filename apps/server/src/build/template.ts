/**
 * The predefined MVP project template.
 *
 * Origin does not ask a model to invent a project structure. The surrounding
 * files are fixed here and written before the Builder runs, so the generated
 * surface is one module and its tests. That is deliberate:
 *
 *   - it is fast, because the model writes two files instead of ten
 *   - it is reliable, because there is nothing to discover or scaffold
 *   - QA is meaningful, because the test harness and entry point are known good
 *
 * The brief still shapes what is built: the generated module implements the
 * opportunity's must-have behaviour, and the CLI harness and README adapt to its
 * title and problem.
 */

import type { Opportunity } from "@origin/contracts";

export interface TemplateVars {
  title: string;
  problem: string;
  solution: string;
  users: string[];
  mustFeatures: string[];
  /** A safe slug used for the package name. */
  slug: string;
}

export function templateVars(opportunity: Opportunity): TemplateVars {
  const brief = opportunity.brief;
  const title = brief?.title ?? opportunity.cluster.label;
  return {
    title,
    problem: brief?.problemStatement ?? opportunity.cluster.problemStatement,
    solution: brief?.proposedSolution ?? "",
    users: brief?.targetUsers ?? [],
    mustFeatures:
      brief?.mvpFeatures.filter((f) => f.priority === "must").map((f) => f.title) ?? [],
    slug:
      title
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, "-")
        .replace(/^-+|-+$/g, "")
        .slice(0, 40) || "origin-mvp",
  };
}

/** package.json for every generated MVP. Fixed, so QA can rely on it. */
export function packageJson(vars: TemplateVars): string {
  return JSON.stringify(
    {
      name: vars.slug,
      version: "0.1.0",
      private: true,
      description: vars.title,
      type: "module",
      scripts: {
        start: "node src/index.mjs",
        test: "node --test",
      },
      engines: { node: ">=18" },
    },
    null,
    2,
  );
}

/**
 * The CLI entry point. It imports the generated core module and demonstrates it
 * on sample input, so running the MVP does something visible.
 */
export function entryPoint(vars: TemplateVars): string {
  return `import { demoInput, run } from './core.mjs';

// Generated by Origin for: ${vars.title.replace(/\n/g, " ")}
// This harness is fixed. The behaviour lives in src/core.mjs.

const input = demoInput();
const result = run(input);

console.log('${vars.title.replace(/'/g, "\\'").replace(/\n/g, " ")}');
console.log('');
console.log('Input:');
console.log(JSON.stringify(input, null, 2));
console.log('');
console.log('Output:');
console.log(JSON.stringify(result, null, 2));
`;
}

export function readme(vars: TemplateVars): string {
  const features =
    vars.mustFeatures.length > 0
      ? vars.mustFeatures.map((f) => `- ${f}`).join("\n")
      : "- Core behaviour described in the problem statement";

  return `# ${vars.title}

${vars.problem}

## What this is

A minimal MVP generated by Origin from an approved opportunity brief. It is a
small Node.js module with a CLI harness, not a production application.

## Scope

${features}

## Run

\`\`\`bash
node src/index.mjs
\`\`\`

## Test

\`\`\`bash
node --test
\`\`\`

## Layout

- \`src/core.mjs\` — the generated behaviour, including \`demoInput()\` and \`run()\`
- \`src/index.mjs\` — fixed CLI harness that runs the module on sample input
- \`core.test.mjs\` — the generated test suite
`;
}

/**
 * The contract for the one module the Builder writes.
 *
 * The interface is fixed so the harness and QA do not depend on invented names.
 * Everything about *what* it computes comes from the brief.
 */
export function builderPrompt(vars: TemplateVars, attempt: number, failures: string[]): string {
  const features =
    vars.mustFeatures.length > 0
      ? vars.mustFeatures.map((f) => `- ${f}`).join("\n")
      : "- Implement the core behaviour described in the problem";

  const parts = [
    "Write exactly two files: src/core.mjs and core.test.mjs.",
    "The other files already exist. Do not create, modify or delete anything else.",
    "",
    "Do not explore the filesystem, do not list directories, do not search the web,",
    "and do not run any command. Everything you need is below.",
    "",
    `PROJECT: ${vars.title}`,
    `PROBLEM: ${vars.problem}`,
    vars.solution ? `APPROACH: ${vars.solution}` : "",
    vars.users.length > 0 ? `USERS: ${vars.users.join(", ")}` : "",
    "",
    "REQUIRED BEHAVIOUR:",
    features,
    "",
    "src/core.mjs must export exactly these:",
    "",
    "  export function demoInput()",
    "    Returns a representative sample input for this problem.",
    "    A plain object or array. No I/O, no randomness.",
    "",
    "  export function run(input)",
    "    Takes that input and returns a result object describing the outcome.",
    "    Pure: same input gives the same output. No I/O, no network, no Date.now().",
    "",
    "You may export additional helper functions.",
    "Use only Node.js built-in modules, or none at all.",
    "Use ES module syntax (import/export). Files use the .mjs extension.",
    "",
    "core.test.mjs must:",
    "  - import { test } from 'node:test' and assert from 'node:assert/strict'",
    "  - import { run, demoInput } from './src/core.mjs'",
    "  - contain at least 3 tests with at least 5 assertions in total",
    "  - test real behaviour: run(demoInput()) returns a sensible result,",
    "    and cover the main rules of the module",
    "  - pass when run with: node --test",
    "",
    "Keep the implementation under 120 lines. Simple and correct beats elaborate.",
  ].filter(Boolean);

  if (attempt > 0 && failures.length > 0) {
    parts.push(
      "",
      `FIX ATTEMPT ${attempt}. The previous attempt failed QA:`,
      ...failures.map((f) => `- ${f.slice(0, 300)}`),
      "",
      "Rewrite both files to fix these specific problems. Keep the exports the same.",
    );
  }

  return parts.join("\n");
}
